/*
 * Spec 101 FR-013, FR-020, FR-070: the renderer's copy of the logo drawings, made from build/logo/*.svg by one function that
 * `npm run icons:build` (scripts/build-icons.js) and `npm run test:logo-assets` both call, so the two cannot drift.
 * Plain Node, no Electron, no dependency, no shell. Each drawing is read as text; its shapes keep `data-slot` and lose the literal
 * `fill`, because in the app the six `--logo-*` tokens (src/renderer/logo.css) paint every slot.
 */
const fs = require('fs');
const path = require('path');

const IDS = ['1', '2', '3', '5']; // the owner's numbers (2026-10-31); there is no icon 4
const SIZES = [1024, 32, 20, 16];
const SLOTS = ['plate', 'gold', 'bot', 'eye', 'cream', 'screen', 'badge'];
const NAMES = {
  1: ['Prompt sovereign', 'A command prompt wearing a crown, three bots below'],
  2: ['Terminal chair', 'A high-backed chair whose back is a terminal'],
  3: ['Figure with badge', 'A crowned figure with a prompt on the chest'],
  5: ['Underscore floor', 'Three bots standing on the prompt’s underscore'],
};
const LOGO_DIR = path.join(__dirname, '..', 'build', 'logo');

/** The file name of icon `id` at `size` (1024 has no suffix). */
const fileName = (id, size) => `icon-${id}${size === 1024 ? '' : '-' + size}.svg`;

/** The shapes of an SVG text, without `fill`, `<title>` and the root element: what goes inside an inline <svg>. */
function innerShapes(svg) {
  const shapes = svg.match(/<(?:rect|path|circle|ellipse|polygon)\b[^>]*\/>/g) || [];
  return shapes.map((s) => s.replace(/\s+fill="[^"]*"/, '')).join('');
}

/** The source of src/renderer/logo-marks.js. `read(file)` returns the text of a file of build/logo. */
function marksSource(read) {
  const rd = read || ((f) => fs.readFileSync(path.join(LOGO_DIR, f), 'utf8'));
  const top = {}, full = {};
  for (const id of IDS) { top[id] = innerShapes(rd(fileName(id, 20))); full[id] = innerShapes(rd(fileName(id, 1024))); }
  return `/* GENERATED by scripts/logo-marks.js (npm run icons:build) from build/logo/*.svg: do not edit by hand. test:logo-assets compares it.
 * Spec 101 FR-020..FR-022, FR-030: the four logo drawings for the top bar (20 px grid) and the Settings preview (1024), the stored
 * choice (localStorage durbar.logo: 1, 2, 3 or 5, anything else is 1) and its early apply before first paint. No network, no IPC. */
(function (root) {
  'use strict';
  const IDS = ${JSON.stringify(IDS)};
  const NAMES = ${JSON.stringify(NAMES)};
  const TOP = ${JSON.stringify(top)};
  const FULL = ${JSON.stringify(full)};
  const KEY = 'durbar.logo';
  const valid = (v) => IDS.indexOf(v) >= 0;
  /* the stored choice; a blocked localStorage or any other value is icon 1 */
  function stored() { try { const v = root.localStorage.getItem(KEY); return valid(v) ? v : '1'; } catch (e) { return '1'; } }
  /* data-logo on <html> and the top bar's drawing; the tile is the plate, the tokens paint the slots */
  function apply(id) {
    const v = valid(id) ? id : '1';
    if (typeof document === 'undefined') return v;
    document.documentElement.setAttribute('data-logo', v);
    const s = document.querySelector('.brand-mark svg');
    if (s && s.getAttribute('data-logo-id') !== v) { s.innerHTML = TOP[v]; s.setAttribute('data-logo-id', v); }
    return v;
  }
  function set(id) { const v = valid(id) ? id : '1'; try { root.localStorage.setItem(KEY, v); } catch (e) { /* kept for this run only */ } return apply(v); }
  function current() { return valid(root.document && root.document.documentElement.getAttribute('data-logo')) ? root.document.documentElement.getAttribute('data-logo') : stored(); }
  /* the 1024 drawing at 64 CSS px for Settings, painted by the same tokens as the top bar (FR-023) */
  function preview(id) { const v = valid(id) ? id : '1'; return '<svg class="logo-pv" data-id="' + v + '" width="64" height="64" viewBox="0 0 1024 1024" aria-hidden="true" focusable="false">' + FULL[v] + '</svg>'; }
  root.DurbarLogo = { IDS, NAMES, TOP, FULL, stored, apply, set, current, preview, valid };
  apply(stored());
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

module.exports = { IDS, SIZES, SLOTS, NAMES, LOGO_DIR, fileName, innerShapes, marksSource };
